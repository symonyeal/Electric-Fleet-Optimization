"""Markdown from collected results (bench/collect.py): the results page and the README block.
Rendering only; every number comes from an admitted bundle or a replay."""


def fmt(x, d=2):
    return "-" if x is None else f"{x:,.{d}f}"


def pct(g):
    return "-" if g is None else f"{100 * g:.3f}%"


def cpu(b):
    """The processor a bundle was measured on."""
    h = (b.get("bundle") or {}).get("host") or (b.get("provenance") or {}).get("host") or {}
    return h.get("cpu", "not recorded")


def results(D):
    """docs/results/README.md."""
    L = ["# Results", "",
         ("Regenerated by `python run_bench.py` from the bundles in this directory. A bundle is "
          "admitted only if it passes the schema check of `bench/schema.py` for its case (clean "
          "code revision, current formulation, unchanged inputs and scenario, a self-consistent "
          "result record, unchanged routes or schedule), or, for a bundle written before that "
          "schema, if [MIGRATION.json](MIGRATION.json) retains it. Every upper bound U is "
          "recomputed here by the independent replay; a replayed route set certifies its own "
          "length whoever produced it, so U may come from any route file that replays. A lower "
          "bound L counts only from an admitted bundle. Bundles that are not admitted are "
          "listed at the end with the reason."), "",
         ("Status fields follow the result contract of [Algorithms](../ALGORITHMS.md) §8: "
          "`solver_status` is the solver's own termination, `validation_status` whether the "
          "replay accepted the returned solution, `certificate_status` whether U and L agree "
          "within tolerance; the public `status` is `optimal` only when certified."), "",
         "## 2019 E instances (Validation §3, EVRP-06)", "",
         ("L is the best admitted lower bound (R1, R2 and R2-RCC, and R0's, since "
          "z(R0) <= z(R1)); U the shortest replayed solution (R1, R2's and R2-RCC's restricted "
          "masters, GSGA). evrp-python's "
          "README values are not replayed. The last columns count segments of U's routes that "
          "pass two or more stations in a row (Routing §4), and name the code revisions of the "
          "admitted bundles."), "",
         ("| Instance | Report value | evrp-python (README) | GSGA replayed | R0 | L | U | Gap | "
          "Verdict | Multi-station segments | Revisions |"),
         "|---|---:|---:|---:|---:|---:|---:|---:|---|---:|---|"]
    for r in D["routing"]:
        L.append(f"| {r['instance']} | {r['report']:.6f} | {r['evrp_python']:.2f} | "
                 f"{fmt(r['gsga'], 6)} | {fmt(r['r0'], 6)} | {fmt(r['L'], 6)} | {fmt(r['U'], 6)} "
                 f"| {pct(r['gap'])} | {r['verdict']} | {fmt(r['segments'], 0)} | "
                 f"{', '.join(r['sources']) or '-'} |")
    if D["duals"]:
        L += ["", "## Interior versus simplex duals in R2 (CG-04)", "",
              ("Seconds are wall-clock on the processor named, and compare only within a row. "
               "The bound is the best (R2.2) from a completed exact pricing; '-' when none "
               "completed in its limit."), "",
              ("| Instance | Iterations (IPM / simplex) | Pricing calls | Seconds | Bound "
               "(IPM / simplex) | Converged | Processor |"), "|---|---:|---:|---:|---:|---|---|"]
        for d in D["duals"]:
            a, b = d["ipm"], d["simplex"]
            pa, pb = cpu(a), cpu(b)
            L.append(f"| {d['instance']} | {a['iterations']} / {b['iterations']} | "
                     f"{a['pricing']} / {b['pricing']} | {a['elapsed']:.1f} / {b['elapsed']:.1f} "
                     f"| {fmt(a['L'], 4)} / {fmt(b['L'], 4)} | {a['converged']} / "
                     f"{b['converged']} | {pa if pa == pb else f'{pa} / {pb}'} |")
    L += transit(D)
    L += grid(D)
    L += excluded(D)
    L += ["", "## Figures", ""]
    if any(r["best"] for r in D["routing"] if r["instance"] == "E-n22-k4"):
        L += ["![E-n22-k4](fig/routes-E-n22-k4.png)", ""]
    if any(d["instance"] == "E-n22-k4" for d in D["duals"]):
        L += ["![R2 duals](fig/r2-duals-E-n22-k4.png)", ""]
    for tag, label in drawn(D):
        L += [f"![{label} timeline](fig/timeline-{tag}.png)", "",
              f"![{label} energy](fig/energy-{tag}.png)", ""]
    return "\n".join(L)


def transit(D):
    L = []
    if D["transit"]:
        L += ["", "## Route 100 (Validation §3, TRN-09)", "",
              ("Illustrative battery, charger and cost parameters (data/scenarios/route100.toml);"
               " costs in illustrative CAD for the modeled window. M0 minimizes the fleet "
               "without batteries; its duties are replayed with the battery and no charging, "
               "which gives their deadhead, their cost where feasible, and the number of buses "
               "that fall below the reserve. M1 values are replayed schedules; the depot's "
               "overnight restoration to s0 B is an external term priced at the depot rate, "
               "never a credit, and its feasibility is not modeled (Models §3a)."), "",
              ("| Window | Trips | M0 fleet | M0 deadhead km | M0 buses below reserve | M0 cost | "
               "M1 fleet | M1 deadhead km | M1 cost U | M1 L | Gap | M1 status |"),
              "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|"]
        for r in D["transit"]:
            row = (f"| {r['label']} | {r['trips']} | {r['m0']['fleet']} | {r['deadhead']:.1f} | "
                   f"{r['below']} | {fmt(r['m0_cost'])} |")
            b = r["m1"]
            if b:
                dh = b["replayed"]["parts"]["deadhead"] / r["v"]["cost"]["deadhead"]
                row += (f" {b['fleet']} | {dh:.1f} | {fmt(b['U'])} | {fmt(b['L'])} | "
                        f"{pct(b['gap_rel'])} | {b['status']} |")
            else:
                row += " - | - | - | - | - | not admitted or not run |"
            L.append(row)
    if D["sourced"]:
        L += ["", "## Route 100 on sourced parameters (Data §3)", "",
              ("Full service day, 2026-10-07. Battery 594 kWh (Nova LFSe+ total capacity) or "
               "285.8 kWh, a derived stress case: the pack that would just give TransLink's "
               "'over 150 km' at the assumed consumption, reserve and ceiling, not the installed "
               "pack. Consumption 1.429 kWh/km (Altoona 40-ft arterial cycle), charging "
               "efficiency 0.90 (Foothill). Energy rates and riders from BC Hydro's published "
               "fleet tariff, taxes excluded; the monthly demand charge divided by 365/12 is a "
               "normalized daily sensitivity weight, not a bill. Charger power, plugs per loop, "
               "the depot, the operating band and the capital and operating costs are "
               "illustrative. Depot recovery is an external term (Models §3a). For context "
               "only, not a validation target: TransLink reports 19 battery-electric buses and "
               "10 on-route chargers system-wide."), "",
              ("| Scenario | M0 duties below reserve | M1 fleet | Plugs | Charged on route, kWh | "
               "Billed demand, kW | Electricity, CAD/day (normalized) | Cost U | L | Gap | "
               "Status |"),
              "|---|---:|---:|---|---:|---:|---:|---:|---:|---:|---|"]
        for r in D["sourced"]:
            b, v = r["m1"], r["v"]
            co, P = v["cost"], b["replayed"]["parts"]
            kwh = sum(sum(d.values()) for d in b["plan"].values()) * v["time"]["delta"] / 3600
            kw = P["peak"] / ((1 + co.get("rider", 0.0)) * co["peak"])
            el = sum(P.get(k, 0.0) for k in ("energy", "depot_energy", "peak", "basic"))
            plugs = ", ".join(f"{v['sites'][s]['name']} {i['n']}" for s, i in b["infra"].items())
            below = "-" if r["below"] is None else f"{r['below']} of {r['m0_fleet']}"
            L.append(f"| {r['what']} | {below} | {b['fleet']} | {plugs or 'none'} | {kwh:,.0f} | "
                     f"{kw:,.0f} | {fmt(el)} | {fmt(b['U'])} | {fmt(b['L'])} | "
                     f"{pct(b['gap_rel'])} | {b['status']} |")
    return L


def grid(D):
    if not D["grid"]:
        return []
    L = ["", "## Charging physics (OA-04)", "",
         ("Each row fixes the loss coefficient alpha (illustrative). M2 and R3 are solved by "
          "outer approximation, M1 and R1 by HiGHS, on the same instance. M2 against M1 compares "
          "cost; R3 against R1 compares the replayed route length, since R3 also prices energy "
          "and dwell time. 'With' is filled only when OA certified its value; the OA gap is on "
          "the model's own objective, and 'Without' carries the status of the model without "
          "losses. The eight-customer R3 row measures the size at which OA stops closing."), "",
         ("| Model pair | Instance | Measure | alpha | Without | With | Increase | OA gap | Status "
          "| Seconds |"),
         "|---|---|---|---:|---:|---:|---:|---:|---|---:|"]
    for g in D["grid"]:
        inc = None if g["base"] is None or g["loss"] is None else g["loss"] - g["base"]
        L.append(f"| {g['pair']} | {g['instance']} | {g['measure']} | {g['alpha']:g} | "
                 f"{fmt(g['base'], 3)} ({g.get('base_status', '-')}) | {fmt(g['loss'], 3)} | "
                 f"{fmt(inc, 3)} | {pct(g.get('gap'))} | {g['status']} | "
                 f"{fmt(g.get('elapsed'), 1)} |")
    return L


def excluded(D):
    if not D["excluded"]:
        return []
    L = ["", "## Bundles not admitted", "",
         ("Kept for the record and never read into a verdict above. `legacy` bundles predate "
          "the schema; their migration decision is in [MIGRATION.json](MIGRATION.json). A "
          "provenance-limited bundle comes from a revision with uncommitted changes: not "
          "shown false, but not reproducible from its revision alone."), "",
         "| Bundle | Revision | Decision | Reasons |", "|---|---|---|---|"]
    for e in sorted(D["excluded"], key=lambda e: e["file"]):
        L.append(f"| {e['file']} | {e.get('revision') or '-'} | {e.get('decision') or '-'} | "
                 f"{', '.join(e['reasons'])} |")
    return L


def drawn(D):
    """(tag, label) of the Route 100 runs drawn: the first admitted illustrative window, then
    each admitted sourced run that charges on route."""
    out = []
    first = next((r for r in D["transit"] if r["m1"]), None)
    if first:
        out.append((first["tag"], first["label"]))
    out += [(r["tag"], f"Route 100, full day, {r['what']}") for r in D["sourced"]
            if r["m1"]["plan"]]
    return out


def summary(D):
    """The results block of the top-level README, between its markers."""
    revs = sorted({s for r in D["routing"] for s in r["sources"]}
                  | {_r(r["m0"]) for r in D["transit"]}
                  | {_r(r["m1"]) for r in D["transit"] if r["m1"]}
                  | {_r(r["m1"]) for r in D["sourced"]})
    L = [("Regenerated by `python run_bench.py` from the admitted bundles in "
          "[docs/results](docs/results/README.md), which name the code revision of each run "
          f"({', '.join(revs) or 'none'}). Every U is a replayed solution; every L comes from a "
          "bundle that passed the schema check or that the migration manifest retains."), "",
         "| Instance | Report value | U (replayed) | L | Gap | Verdict |",
         "|---|---:|---:|---:|---:|---|"]
    for r in D["routing"]:
        L.append(f"| {r['instance']} | {r['report']:.6f} | {fmt(r['U'], 6)} | {fmt(r['L'], 6)} "
                 f"| {pct(r['gap'])} | {r['verdict']} |")
    d = next((d for d in D["duals"] if d["instance"] == "E-n22-k4"), None)
    if d:
        a, b = d["ipm"], d["simplex"]
        L += ["", (f"Column generation on E-n22-k4 reached the bound {fmt(a['L'], 4)} with "
                   f"interior duals in {a['elapsed']:.1f} s and {fmt(b['L'], 4)} with simplex "
                   f"duals in {b['elapsed']:.1f} s.")]
    for r in D["transit"]:
        if r["until"] is not None and not r["m1"]:
            continue
        s = (f"{r['label']}: {r['trips']} trips need {r['m0']['fleet']} buses without batteries "
             f"(M0, certified by matching against a replayed cover).")
        if r["m1"]:
            b = r["m1"]
            s += (f" M1, with the illustrative {r['v']['battery']['B']:g} kWh battery, schedules "
                  f"it with {b['fleet']} buses and {sum(i['n'] for i in b['infra'].values())} "
                  f"plugs, cost {fmt(b['U'])} against the bound {fmt(b['L'])} (gap "
                  f"{pct(b['gap_rel'])}, {b['status']}).")
        L += ["", s]
    for r in D["sourced"]:
        b = r["m1"]
        L += ["", (f"On sourced parameters ({r['what']}; [Data](docs/DATA.md) §3), M1 "
                   f"schedules the day with {b['fleet']} buses, cost {fmt(b['U'])} in "
                   f"normalized CAD/day against the bound {fmt(b['L'])} ({b['status']}).")]
    return L


def _r(b):
    if b is None:
        return "-"
    if "bundle" in b:
        return b["bundle"]["code"]["commit"][:7]
    return (b.get("provenance") or {}).get("revision") or "unrecorded"
